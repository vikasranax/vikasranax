def detect_language(path_bytes):
    low = path_bytes.decode("utf-8", "ignore").lower()
    parts = low.split("/")
    name = parts[-1]
    if any(p in SKIP_DIRS for p in parts[:-1]):
        return None
    if name in SKIP_FILENAMES or name.endswith((".min.js", ".min.css", ".min.mjs", ".d.ts", ".map")):
        return None
    if name == "dockerfile" or name.startswith("dockerfile."):
        return "Dockerfile"
    return EXT_LANG.get(os.path.splitext(name)[1])


def count_lines(path):
    """Non-blank lines; 0 for binary, huge, minified or generated files."""
    try:
        if path.stat().st_size > 1_000_000:
            return 0
        data = path.read_bytes()
    except OSError:
        return 0
    if b"\0" in data[:8192]:
        return 0
    head = data[:2048].lower()
    if any(m in head for m in GENERATED_MARKERS):
        return 0
    lines = data.splitlines()
    if not lines or len(data) / len(lines) > 300:       # minified
        return 0
    return sum(1 for ln in lines if ln.strip())


def measure_repo(full_name, dest):
    """Clone (shallow is fine for LOC) and return {language: lines}."""
    auth = f"x-access-token:{TOKEN}@" if TOKEN else ""
    url = f"https://{auth}github.com/{full_name}.git"
    env = dict(os.environ, GIT_TERMINAL_PROMPT="0")
    try:
        subprocess.run(["git", "clone", "--depth", "1", "--quiet", url, str(dest)],
                       check=True, timeout=300, env=env,
                       stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)
        listed = subprocess.run(["git", "-C", str(dest), "ls-files", "-z"],
                                capture_output=True, check=True).stdout
    except Exception as e:
        print(f"clone/measure failed for {full_name}: {mask(e)}", file=sys.stderr)
        return {}
    by_lang = {}
    for f in listed.split(b"\0"):
        if not f:
            continue
        lang = detect_language(f)
        if not lang:
            continue
        n = count_lines(dest / f.decode("utf-8", "ignore"))
        if n:
            by_lang[lang] = by_lang.get(lang, 0) + n
    return by_lang


