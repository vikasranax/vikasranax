def ordinal_suffix(day):
    if 11 <= day <= 13:
        return "th"
    return {1: "st", 2: "nd", 3: "rd"}.get(day % 10, "th")


def format_ist_now():
    utc = datetime.datetime.now(datetime.timezone.utc)
    ist = utc + datetime.timedelta(hours=5, minutes=30)
    return ist.strftime(f"%d{ordinal_suffix(ist.day)} %B %Y · %I:%M %p IST")


def mask(text):
    text = str(text)
    return text.replace(TOKEN, "***") if TOKEN else text


def _request(url, payload=None):
    data = json.dumps(payload).encode() if payload is not None else None
    req = urllib.request.Request(url, data=data)
    req.add_header("Accept", "application/vnd.github+json")
    req.add_header("User-Agent", f"{USERNAME}-banner-generator")
    if data:
        req.add_header("Content-Type", "application/json")
    if TOKEN:
        req.add_header("Authorization", f"Bearer {TOKEN}")
    try:
        with urllib.request.urlopen(req, timeout=REQUEST_TIMEOUT) as resp:
            return json.loads(resp.read().decode() or "null"), resp.headers
    except Exception as e:
        print(f"API error for {url}: {mask(e)}", file=sys.stderr)
        return None, {}


def api_call(url):
    return _request(url)[0]


