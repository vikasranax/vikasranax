def fetch_repos():
    me = api_call("https://api.github.com/user") if TOKEN else None
    is_owner = isinstance(me, dict) and str(me.get("login", "")).lower() == USERNAME.lower()
    if is_owner:
        base = "https://api.github.com/user/repos?affiliation=owner&visibility=all"
    else:
        base = f"https://api.github.com/users/{USERNAME}/repos?type=owner"
    repos, page = [], 1
    while page <= 10:
        data = api_call(f"{base}&per_page=100&page={page}&sort=updated")
        if not isinstance(data, list) or not data:
            break
        repos.extend(data)
        if len(data) < 100:
            break
        page += 1
    out = []
    for r in repos:
        if r.get("fork") and not INCLUDE_FORKS:
            continue
        if r.get("private") and not INCLUDE_PRIVATE:
            continue
        out.append(r)
    return out


