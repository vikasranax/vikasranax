def fetch_stats():
    user = api_call(f"https://api.github.com/users/{USERNAME}") or {}
    created = None
    try:
        created = datetime.datetime.strptime(user["created_at"], "%Y-%m-%dT%H:%M:%SZ") \
            .replace(tzinfo=datetime.timezone.utc)
    except Exception:
        pass

    repos = fetch_repos()
    lang_lines, stars = {}, 0
    tmp = Path(tempfile.mkdtemp(prefix="banner-repos-"))
    print(f"{'repo':32} {'lines':>9}")
    try:
        for r in repos:
            stars += r.get("stargazers_count", 0)
            full = r.get("full_name", f"{USERNAME}/{r['name']}")
            by_lang = measure_repo(full, tmp / r["name"])
            for lang, n in by_lang.items():
                lang_lines[lang] = lang_lines.get(lang, 0) + n
            print(f"{r['name'][:32]:32} {sum(by_lang.values()):>9,}")
    finally:
        shutil.rmtree(tmp, ignore_errors=True)

    per_year = commits_by_year(created)
    if per_year is not None:
        total_commits = sum(per_year.values())
        source = "graphql"
    else:
        total_commits = sum(rest_commit_count(r.get("full_name", f"{USERNAME}/{r['name']}")) for r in repos)
        source = "rest-fallback"
    print(f"commits: {total_commits:,} ({source})")

    total_loc = sum(lang_lines.values())
    top = sorted(lang_lines.items(), key=lambda x: x[1], reverse=True)[:TOP_LANGUAGES]
    denom = total_loc or 1
    languages = [(lang, n, n / denom * 100) for lang, n in top]

    years_active = None
    if created:
        years_active = max(1, round((datetime.datetime.now(datetime.timezone.utc) - created).days / 365.25))

    return {
        "name": user.get("name") or USERNAME,
        "repos": len(repos), "stars": stars,
        "commits": total_commits, "loc": total_loc,
        "languages": languages,
        "per_year": per_year or {},
        "since": created.strftime("%b %Y") if created else "",
        "years_active": years_active,
    }


