def commits_by_year(created):
    """GraphQL, one aliased window per year. Returns {year: commits} or None."""
    if not TOKEN or not created:
        return None
    now = datetime.datetime.now(datetime.timezone.utc)
    iso = lambda d: d.strftime("%Y-%m-%dT%H:%M:%SZ")
    years = list(range(created.year, now.year + 1))
    parts = []
    for y in years:
        start = max(created, datetime.datetime(y, 1, 1, tzinfo=datetime.timezone.utc))
        end = min(datetime.datetime(y, 12, 31, 23, 59, 59, tzinfo=datetime.timezone.utc), now)
        parts.append(f'y{y}: contributionsCollection(from: "{iso(start)}", to: "{iso(end)}") '
                     f'{{ totalCommitContributions }}')
    query = "query($login:String!){ user(login:$login){ " + " ".join(parts) + " } }"
    data, _ = _request("https://api.github.com/graphql",
                       {"query": query, "variables": {"login": USERNAME}})
    try:
        u = data["data"]["user"]
        return {y: int(u[f"y{y}"]["totalCommitContributions"]) for y in years}
    except Exception:
        print(f"GraphQL commit query failed: {mask(json.dumps(data)[:300])}", file=sys.stderr)
        return None


def rest_commit_count(full_name):
    """Fallback: commits authored by USERNAME in one repo (default branch)."""
    url = f"https://api.github.com/repos/{full_name}/commits?author={USERNAME}&per_page=1"
    data, headers = _request(url)
    if not isinstance(data, list):
        return 0
    m = re.search(r'[?&]page=(\d+)>; rel="last"', headers.get("Link", "") if headers else "")
    return int(m.group(1)) if m else len(data)


